import { ColorTheme, FontPair, WebsiteConfig } from '../types/site';

export const getFontHeadingClass = (fontPair: FontPair): string => {
  switch (fontPair) {
    case 'modern-sans':
      return 'font-display-jakarta tracking-tight';
    case 'geometric':
      return 'font-display-outfit tracking-normal';
    case 'editorial-serif':
      return 'font-display-serif tracking-normal font-medium';
    default:
      return 'font-display-jakarta tracking-tight';
  }
};

export const getFontBodyClass = (fontPair: FontPair): string => {
  switch (fontPair) {
    case 'modern-sans':
    case 'geometric':
      return 'font-body-sans';
    case 'editorial-serif':
      return 'font-body-sans';
    default:
      return 'font-body-sans';
  }
};

